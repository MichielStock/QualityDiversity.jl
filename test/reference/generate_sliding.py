# Reference values for test_sliding.jl: the boundaries and elites of pyribs's
# SlidingBoundariesArchive after each solution of a sequence, added one at a time.
# `python3 generate_sliding.py` rewrites `sliding.jl` next to it. Needs ribs 0.12.0; QDax
# has no sliding boundaries.
#
# Fitness and descriptors are drawn from continuous distributions, so no two fitness
# values tie, and a descriptor lies within pyribs's tolerance of 1e-6 below a boundary
# with negligible probability. Many descriptors fall outside the initial ranges, so the
# boundaries widen at a remap.
#
# pyribs 0.12.0 clips the descriptors to the old bounds while it adds the solutions back
# during a remap, since it updates its bounds only afterwards; when the boundaries widen,
# solutions land in the wrong cells. The script corrects that, so that `index_of` always
# clips to the current boundaries, as SlidingBoundariesArchive does.
import numpy as np
from ribs.archives import SlidingBoundariesArchive

_index_of = SlidingBoundariesArchive.index_of


def index_of(self, measures):
    self._lower_bounds = np.array([b[0] for b in self._boundaries])
    self._upper_bounds = np.array([b[d] for b, d in zip(self._boundaries, self._dims)])
    return _index_of(self, measures)


SlidingBoundariesArchive.index_of = index_of

rng = np.random.default_rng(17)
lines = ["# Generated by generate_sliding.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines.append("const sliding_cases = [")
for dims, remap_frequency, buffer_capacity, total in (((4, 3), 7, 20, 60), ((5,), 10, 10, 45),
                                                       ((3, 3), 5, 12, 40), ((6, 2), 25, 100, 120)):
    ranges = [(-1.0, 1.0)] * len(dims)
    descriptors = rng.normal(scale=0.8, size=(total, len(dims)))
    fitness = rng.normal(size=total)
    archive = SlidingBoundariesArchive(solution_dim=1, dims=list(dims), ranges=ranges,
                                       remap_frequency=remap_frequency, buffer_capacity=buffer_capacity)
    boundaries, kept = [], []
    for i in range(total):
        archive.add_single([float(i)], fitness[i], descriptors[i])
        boundaries.append(np.concatenate([np.asarray(b) for b in archive.boundaries]))
        kept.append(sorted(int(s) + 1 for s in archive.data("solution")[:, 0]))
    lines.append(f"    (dims={tuple(dims)!r}, remap_frequency={remap_frequency}, buffer_capacity={buffer_capacity},".replace(",)", ",)"))
    lines.append(f"     fitness={fmt(fitness)},")
    lines.append(f"     descriptors={fmt(descriptors)},")
    lines.append("     boundaries=[" + ", ".join(fmt(b) for b in boundaries) + "],")
    lines.append("     kept=[" + ", ".join("[" + ", ".join(map(str, k)) + "]" for k in kept) + "]),")
lines.append("]")

with open(__file__.replace("generate_sliding.py", "sliding.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
