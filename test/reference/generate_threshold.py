# Reference values for test_threshold.jl: what pyribs's GridArchive with a learning rate
# (the archive of CMA-MAE) reports and keeps after each batch of a sequence. `python3
# generate_threshold.py` rewrites `threshold.jl` next to it. Needs ribs 0.12.0; QDax has
# no threshold archive.
#
# Every solution carries its number as its genotype. Four cells receive batches of eight,
# so a cell often takes several solutions of one batch, and some fitness values lie below
# `threshold_min`. The fitness values are drawn from a continuous distribution, so no two
# tie and the tie rules of the libraries do not matter.
import numpy as np
from ribs.archives import GridArchive

rng = np.random.default_rng(17)
lines = ["# Generated by generate_threshold.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


def ints(a):
    return "[" + ", ".join(str(int(v)) for v in np.ravel(a)) + "]"


cells, batch, batches, threshold_min = 4, 8, 6, -1.0
lines.append("const threshold_cases = [")
for learning_rate in (1.0, 0.5, 0.1):
    total = batch * batches
    fitness = rng.normal(scale=2.0, size=total)
    descriptors = rng.uniform(size=total)
    archive = GridArchive(solution_dim=1, dims=[cells], ranges=[(0, 1)],
                          learning_rate=learning_rate, threshold_min=threshold_min)
    statuses, values, thresholds, elites = [], [], [], []
    for b in range(batches):
        ids = np.arange(b * batch, (b + 1) * batch)
        info = archive.add(ids[:, None].astype(float) + 1, fitness[ids], descriptors[ids, None])
        statuses.extend(info["status"])
        values.extend(info["value"])
        index, threshold, solution = archive.data(["index", "threshold", "solution"], return_type="tuple")
        per_cell = np.full(cells, threshold_min)
        per_cell[index] = threshold
        kept = np.zeros(cells, dtype=int)
        kept[index] = solution[:, 0]
        thresholds.append(per_cell)
        elites.append(kept)
    lines.append(f"    (learning_rate={learning_rate}, threshold_min={threshold_min}, cells={cells}, batch={batch},")
    lines.append(f"     fitness={fmt(fitness)},")
    lines.append(f"     descriptors={fmt(descriptors)},")
    # pyribs statuses: 0 rejected, 1 improved, 2 new cell
    lines.append(f"     statuses={ints(statuses)},")
    lines.append(f"     values={fmt(values)},")
    # after each batch, per cell: the threshold, and the number of the elite (0 for none)
    lines.append(f"     thresholds={fmt(thresholds)},")
    lines.append(f"     elites={ints(elites)}),")
lines.append("]")

with open(__file__.replace("generate_threshold.py", "threshold.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
