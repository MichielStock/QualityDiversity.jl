# Reference values for test_density.jl: the densities that pyribs's DensityArchive reports
# for a sequence of batches. `python3 generate_density.py` rewrites `density.jl` next to
# it. Needs ribs 0.12.0; QDax has no density archive.
#
# The buffer holds every descriptor of a sequence, so reservoir sampling never replaces
# one and the densities do not depend on random draws.
import numpy as np
from ribs.archives import DensityArchive

rng = np.random.default_rng(3)
lines = ["# Generated by generate_density.py; do not edit."]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines.append("const density_cases = [")
for dims, bandwidth, batch, batches in ((2, 0.3, 10, 5), (1, 0.05, 7, 6), (3, 1.0, 20, 3)):
    total = batch * batches
    descriptors = rng.normal(size=(total, dims))
    archive = DensityArchive(measure_dim=dims, buffer_size=total, bandwidth=bandwidth)
    densities = []
    for b in range(batches):
        info = archive.add(None, None, descriptors[b * batch:(b + 1) * batch])
        densities.extend(info["density"])
    lines.append(f"    (dims={dims}, bandwidth={bandwidth}, batch={batch},")
    lines.append(f"     descriptors={fmt(descriptors)},")
    lines.append(f"     densities={fmt(densities)}),")
lines.append("]")

with open(__file__.replace("generate_density.py", "density.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
