# Reference values for test_gradients.jl: the rounds of pyribs's
# GradientArborescenceEmitter (CMA-MEGA) on a fixed problem, with the coefficients of every
# round fixed in advance. `python3 generate_mega.py` rewrites `mega.jl` next to it. Needs
# ribs 0.12.0.
#
# The evolution strategy of the coefficients is replaced by one that returns the scripted
# coefficients and records the ranking and the number of parents it is told, so the
# reference checks the branches, the ranking, the parent count and the steps of the
# solution point, but not the strategy itself, which test_evolution_strategies.jl checks.
# The restart rule is "basic" and the scripted strategy never stops, so no round restarts.
import numpy as np
from ribs.archives import GridArchive
from ribs.emitters import GradientArborescenceEmitter

rng = np.random.default_rng(5)
n, m, batch, rounds = 6, 2, 8, 5
h = n // 2
center = rng.normal(size=n)


def evaluate(x):
    # A smooth objective and linear measures, with their Jacobian.
    objective = -np.sum((x - center) ** 2) + np.sin(x[0])
    measures = np.array([x[:h].mean(), x[h:].mean()])
    jac = np.zeros((1 + m, n))
    jac[0] = -2 * (x - center)
    jac[0, 0] += np.cos(x[0])
    jac[1, :h] = 1 / h
    jac[2, h:] = 1 / (n - h)
    return objective, measures, jac


coefficients = [rng.normal(scale=2.0, size=(batch, 1 + m)) for _ in range(rounds)]
x0 = rng.normal(size=n)


class Scripted:
    def __init__(self):
        self.round = 0
        self.told = []
        self.batch_size = batch

    def ask(self):
        return coefficients[self.round].copy()

    def tell(self, ranking_indices, ranking_values, num_parents):
        self.told.append((list(map(int, ranking_indices)), int(num_parents)))
        self.round += 1

    def check_stop(self, ranking_values):
        return False

    def reset(self, mean):
        pass


def run(grad_opt, lr):
    archive = GridArchive(solution_dim=n, dims=[10, 10], ranges=[(-2, 2), (-2, 2)])
    emitter = GradientArborescenceEmitter(
        archive, x0=x0, sigma0=1.0, lr=lr, grad_opt=grad_opt, batch_size=batch,
        restart_rule="basic", seed=1)
    scripted = Scripted()
    emitter._opt = scripted
    thetas, branches = [], []
    for _ in range(rounds):
        theta = emitter.ask_dqd()
        obj, meas, jac = evaluate(theta[0])
        info = archive.add(theta, [obj], [meas])
        emitter.tell_dqd(theta, [obj], [meas], jac[None], info)
        xs = emitter.ask()
        evs = [evaluate(x) for x in xs]
        objs = np.array([e[0] for e in evs])
        meass = np.array([e[1] for e in evs])
        info = archive.add(xs, objs, meass)
        emitter.tell(xs, objs, meass, info)
        branches.append(xs.copy())
        thetas.append(emitter._grad_opt.theta.copy())
    return thetas, branches, scripted.told


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


lines = ["# Generated by generate_mega.py; do not edit."]
lines.append(f"const mega_center = {fmt(center)}")
lines.append(f"const mega_x0 = {fmt(x0)}")
# Each round's coefficients as a (1 + m) × batch matrix, one column per candidate.
lines.append("const mega_coefficients = [" + ",\n    ".join(
    f"reshape({fmt(c)}, {1 + m}, {batch})" for c in coefficients) + "]")
for name, opt, lr in [("adam", "adam", 0.05), ("ascent", "gradient_ascent", 0.5)]:
    thetas, branches, told = run(opt, lr)
    lines.append(f"const mega_{name}_thetas = [" + ",\n    ".join(fmt(t) for t in thetas) + "]")
    lines.append(f"const mega_{name}_branches = [" + ",\n    ".join(
        f"reshape({fmt(b)}, {n}, {batch})" for b in branches) + "]")
    lines.append(f"const mega_{name}_orders = {[[i + 1 for i in t[0]] for t in told]}")
    lines.append(f"const mega_{name}_parents = {[t[1] for t in told]}")

with open(__file__.replace("generate_mega.py", "mega.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
