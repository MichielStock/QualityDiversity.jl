# Reference values for test_metrics.jl: CQD scores that pyribs's cqd_score computes for
# the elites of an archive and given targets. `python3 generate_cqd.py` rewrites `cqd.jl`
# next to it. Needs ribs 0.12.0; QDax has no CQD score.
import numpy as np
from ribs.archives import GridArchive, cqd_score

rng = np.random.default_rng(23)
lines = ["# Generated by generate_cqd.py; do not edit.", "const cqd_cases = ["]


def fmt(a):
    return "[" + ", ".join(repr(float(v)) for v in np.ravel(a)) + "]"


for dims, n, iterations, num_targets, penalties, obj_range, dist_max in (
        ((20, 20), 400, 3, 50, 5, (-3.0, 2.0), 2 * np.sqrt(2)),
        ((8, 8, 8), 300, 2, 30, [0.0, 0.3, 0.9, 1.5], (-1.0, 4.0), 1.7),
        ((10,), 40, 4, 10, 1, (0.0, 1.0), 2.0)):
    k = len(dims)
    archive = GridArchive(solution_dim=1, dims=list(dims), ranges=[(-1, 1)] * k)
    archive.add(np.zeros((n, 1)), rng.normal(size=n), rng.uniform(-1, 1, size=(n, k)))
    targets = rng.uniform(-1, 1, size=(iterations, num_targets, k))
    result = cqd_score(archive, iterations=iterations, target_points=targets, penalties=penalties,
                       obj_min=obj_range[0], obj_max=obj_range[1], dist_max=dist_max)
    lines.append(f"    (dims={k}, fitness_range={obj_range}, distance_max={float(dist_max)!r}, "
                 f"penalties={penalties if isinstance(penalties, int) else fmt(penalties)},")
    lines.append(f"     fitness={fmt(archive.data('objective'))},")
    lines.append(f"     descriptors={fmt(archive.data('measures'))},")
    lines.append(f"     targets={fmt(targets)}, num_targets={num_targets},")
    lines.append(f"     scores={fmt(result.scores)}),")
lines.append("]")

with open(__file__.replace("generate_cqd.py", "cqd.jl"), "w") as f:
    f.write("\n".join(lines) + "\n")
